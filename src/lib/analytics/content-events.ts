export const ContentAnalyticsEventSchema = z
  .object({
    name: ContentEventNameSchema,
    properties: ContentEventPropertiesSchema,
  })
  .strict();

export type ContentAnalyticsEvent = z.infer<typeof ContentAnalyticsEventSchema>;

/**
 * Phase 3 defines the privacy boundary but intentionally has no analytics
 * vendor. A future adapter may accept only values parsed by this function.
 */
export function createContentAnalyticsEvent(
  event: ContentAnalyticsEvent,
): ContentAnalyticsEvent {
  return ContentAnalyticsEventSchema.parse(event);
}
